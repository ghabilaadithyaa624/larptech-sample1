-- =============================================================================
-- 0001_data_integrity
--
-- De-duplicates the waitlist, normalises stored email addresses, constrains lead
-- status, and tightens the indexes that back those invariants.
--
-- !! READ BEFORE APPLYING !!
-- The data-repair section below is DESTRUCTIVE: it deletes waitlist rows that are
-- duplicates of an existing signup, and rewrites every stored email address.
-- It exists because the two new constraints cannot be created while violating
-- rows exist — PostgreSQL will refuse. Review the two SELECTs under "inspect"
-- below first, on a copy of production, and confirm the row counts are what you
-- expect. Do not run this blind against the production database.
--
-- The rows removed by the de-duplicate step are duplicates of a signup already
-- retained: same address ignoring case, same product. No distinct signup is lost.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- INSPECT FIRST (read-only; safe to run anywhere)
--
--   -- waitlist rows that would be deleted by the de-duplicate step:
--   SELECT lower(btrim(email)) AS addr, product, count(*), array_agg(id ORDER BY created_at)
--   FROM waitlist GROUP BY 1, 2 HAVING count(*) > 1;
--
--   -- leads whose status is not in the allowed set (these will be reset to 'new'):
--   SELECT status, count(*) FROM leads
--   WHERE status NOT IN ('new','contacted','qualified','closed','spam')
--   GROUP BY 1 ORDER BY 2 DESC;
-- -----------------------------------------------------------------------------

-- -----------------------------------------------------------------------------
-- 1. DATA REPAIR  (destructive — see the warning above)
--
-- ORDER MATTERS: de-duplicate runs BEFORE normalisation, not after.
--
-- The outgoing unique index is on the raw `email` text, but it is still in force
-- during step 1b. Normalising first would collapse 'Ada@Example.com' and
-- 'ada@example.com' onto the same key while that index exists, and the UPDATE
-- would abort with a unique violation before the index could be replaced. Verified
-- against a database seeded with exactly that shape of data.
-- -----------------------------------------------------------------------------

-- 1a. De-duplicate the waitlist, keeping the earliest signup per
--     (address ignoring case, product). Without this the unique index below fails
--     to build wherever a case-variant duplicate already exists.
--     Distinct signups (different address or different product) are untouched.
DELETE FROM "waitlist" WHERE "id" NOT IN (
  SELECT DISTINCT ON (lower(btrim("email")), "product") "id"
  FROM "waitlist"
  ORDER BY lower(btrim("email")), "product", "created_at" ASC, "id" ASC
);
--> statement-breakpoint

-- 1b. Normalise every stored address: trim surrounding whitespace, lower-case.
--     Emails are now normalised at the API boundary too (see normaliseEmail in
--     src/lib/validators.ts), so this is a one-time backfill of rows written
--     before that existed. Safe now that step 1a has removed the case variants.
UPDATE "leads" SET "email" = lower(btrim("email"))
WHERE "email" <> lower(btrim("email"));
--> statement-breakpoint
UPDATE "waitlist" SET "email" = lower(btrim("email"))
WHERE "email" <> lower(btrim("email"));
--> statement-breakpoint

-- 1c. Reset any lead status outside the allowed set before the CHECK lands.
--     `status` was previously free text, so a typo would otherwise block the
--     migration. 'new' is the original default and the safe catch-all.
UPDATE "leads" SET "status" = 'new'
WHERE "status" IS NULL
   OR btrim("status") NOT IN ('new', 'contacted', 'qualified', 'closed', 'spam');
--> statement-breakpoint

-- -----------------------------------------------------------------------------
-- 2. SCHEMA CHANGES  (generated by drizzle-kit from src/db/schema.ts)
-- -----------------------------------------------------------------------------

DROP INDEX "leads_email_idx";--> statement-breakpoint
DROP INDEX "waitlist_email_product_idx";--> statement-breakpoint
CREATE INDEX "leads_email_created_at_idx" ON "leads" USING btree ("email","created_at");--> statement-breakpoint
CREATE INDEX "leads_status_idx" ON "leads" USING btree ("status");--> statement-breakpoint
CREATE UNIQUE INDEX "waitlist_email_product_idx" ON "waitlist" USING btree (lower("email"),"product");--> statement-breakpoint
ALTER TABLE "leads" ADD CONSTRAINT "leads_status_check" CHECK ("leads"."status" in ('new', 'contacted', 'qualified', 'closed', 'spam'));
